def _permutation_sign(values: tuple[int, ...]) -> int:
    inversions = sum(
        values[left] > values[right]
        for left in range(len(values))
        for right in range(left + 1, len(values))
    )
    return -1 if inversions % 2 else 1


def _antisymmetrize_pair(tensor: np.ndarray) -> np.ndarray:
    return 0.5 * (tensor - tensor.T)


def _antisymmetrize_quad(tensor: np.ndarray) -> np.ndarray:
    # Project within the first and second index pairs, then sum the six
    # S4/(S2 x S2) cosets. This is the same normalized 24-permutation
    # antisymmetrizer with fewer full rank-four passes.
    pair_antisymmetric = 0.25 * (
        tensor
        - tensor.transpose(1, 0, 2, 3)
        - tensor.transpose(0, 1, 3, 2)
        + tensor.transpose(1, 0, 3, 2)
    )
    return (
        pair_antisymmetric
        - pair_antisymmetric.transpose(0, 2, 1, 3)
        + pair_antisymmetric.transpose(0, 2, 3, 1)
        + pair_antisymmetric.transpose(2, 0, 1, 3)
        - pair_antisymmetric.transpose(2, 0, 3, 1)
        + pair_antisymmetric.transpose(2, 3, 0, 1)
    ) / 6.0


def _pair_square(pair: np.ndarray) -> np.ndarray:
    return (
        np.einsum("ij,kl->ijkl", pair, pair, optimize=("einsum_path", (0, 1)))
        - np.einsum("ik,jl->ijkl", pair, pair, optimize=("einsum_path", (0, 1)))
        + np.einsum("il,jk->ijkl", pair, pair, optimize=("einsum_path", (0, 1)))
    )


def _pair_square_jvp(pair: np.ndarray, direction: np.ndarray) -> np.ndarray:
    return (
        np.einsum("ij,kl->ijkl", direction, pair, optimize=("einsum_path", (0, 1)))
        + np.einsum("ij,kl->ijkl", pair, direction, optimize=("einsum_path", (0, 1)))
        - np.einsum("ik,jl->ijkl", direction, pair, optimize=("einsum_path", (0, 1)))
        - np.einsum("ik,jl->ijkl", pair, direction, optimize=("einsum_path", (0, 1)))
        + np.einsum("il,jk->ijkl", direction, pair, optimize=("einsum_path", (0, 1)))
        + np.einsum("il,jk->ijkl", pair, direction, optimize=("einsum_path", (0, 1)))
    )


def _mode_product(matrix: np.ndarray, tensor: np.ndarray, axis: int) -> np.ndarray:
    transformed = np.tensordot(matrix, tensor, axes=(1, axis))
    return np.moveaxis(transformed, 0, axis)


def _mode_product_nonzero_columns(
    matrix: np.ndarray,
    tensor: np.ndarray,
    axis: int,
) -> np.ndarray:
    columns = np.flatnonzero(np.any(matrix != 0.0, axis=0))
    if columns.size == matrix.shape[1]:
        return _mode_product(matrix, tensor, axis)
    selected = np.take(tensor, columns, axis=axis)
    return _mode_product(matrix[:, columns], selected, axis)


def _mode_product_identity_plus(
    matrix: np.ndarray,
    tensor: np.ndarray,
    axis: int,
) -> np.ndarray:
    if matrix.shape[0] != matrix.shape[1]:
        return _mode_product(matrix, tensor, axis)
    deviation = matrix - np.eye(matrix.shape[0], dtype=matrix.dtype)
    columns = np.flatnonzero(np.any(deviation != 0.0, axis=0))
    if columns.size == matrix.shape[1]:
        return _mode_product(matrix, tensor, axis)
    if not columns.size:
        return np.asarray(tensor)
    selected = np.take(tensor, columns, axis=axis)
    return tensor + _mode_product(deviation[:, columns], selected, axis)


def _transform_quad(matrix: np.ndarray, tensor: np.ndarray) -> np.ndarray:
    result = np.asarray(tensor)
    for axis in range(4):
        result = _mode_product_identity_plus(matrix, result, axis)
    return result


def _transform_quad_jvp(
    matrix: np.ndarray,
    direction_matrix: np.ndarray,
    tensor: np.ndarray,
    direction_tensor: np.ndarray,
) -> np.ndarray:
    result = _transform_quad(matrix, direction_tensor)
    for tangent_axis in range(4):
        term = np.asarray(tensor)
        for axis in range(4):
            term = (
                _mode_product_nonzero_columns(direction_matrix, term, axis)
                if axis == tangent_axis
                else _mode_product_identity_plus(matrix, term, axis)
            )
        result += term
    return result


@lru_cache(maxsize=None)
def _topology_edges(
    loops: tuple[int, ...],
    cross_counts: tuple[int, ...],
) -> tuple[tuple[tuple[int, int], tuple[int, int]], ...]:
    vertex_count = len(loops)
    vertex_pairs = tuple(
        (left, right)
        for left in range(vertex_count)
        for right in range(left + 1, vertex_count)
    )
    free = [list(range(4)) for _ in range(vertex_count)]
    edges: list[tuple[tuple[int, int], tuple[int, int]]] = []
    for vertex, count in enumerate(loops):
        for _ in range(count):
            edges.append(
                (
                    (vertex, free[vertex].pop(0)),
                    (vertex, free[vertex].pop(0)),
                )
            )
    for (left, right), count in zip(vertex_pairs, cross_counts):
        for _ in range(count):
            edges.append(
                (
                    (left, free[left].pop(0)),
                    (right, free[right].pop(0)),
                )
            )
    if any(free):
        raise RuntimeError("invalid generated Ser topology")
    return tuple(edges)


@lru_cache(maxsize=None)
def _term_subscripts(
    loops: tuple[int, ...],
    cross_counts: tuple[int, ...],
    removed_edges: tuple[int, ...],
) -> tuple[str, tuple[int, ...]]:
    edges = _topology_edges(loops, cross_counts)
    if 2 * len(edges) > len(string.ascii_letters):
        raise RuntimeError("Ser topology exceeds NumPy's einsum label limit")
    labels = iter(string.ascii_letters)
    vertex_labels = [[""] * 4 for _ in loops]
    edge_labels: list[str] = []
    for first, second in edges:
        left = next(labels)
        right = next(labels)
        vertex_labels[first[0]][first[1]] = left
        vertex_labels[second[0]][second[1]] = right
        edge_labels.append(left + right)
    inputs = [
        value for index, value in enumerate(edge_labels) if index not in removed_edges
    ]
    inputs.extend("".join(value) for value in vertex_labels)
    output = "".join(edge_labels[index] for index in removed_edges)
    ranks = tuple([2] * (len(edges) - len(removed_edges)) + [4] * len(loops))
    return ",".join(inputs) + "->" + output, ranks


@lru_cache(maxsize=None)
def _einsum_path(subscripts: str, ranks: tuple[int, ...]) -> tuple[object, ...]:
    # All indices have the same quasiparticle dimension.  A dimension-two
    # planning problem therefore selects the same formal contraction tree
    # without allocating molecular-sized planning arrays.
    operands = [np.empty((2,) * rank) for rank in ranks]
    path, _report = np.einsum_path(subscripts, *operands, optimize="greedy")
    return tuple(path)


def _contract_term(
    covariance: np.ndarray,
    t2: np.ndarray,
    loops: tuple[int, ...],
    cross_counts: tuple[int, ...],
    removed_edges: tuple[int, ...],
) -> np.ndarray:
    subscripts, ranks = _term_subscripts(loops, cross_counts, removed_edges)
    edge_count = len(_topology_edges(loops, cross_counts))
    operands = [covariance] * (edge_count - len(removed_edges)) + [t2] * len(loops)
    return np.einsum(
        subscripts,
        *operands,
        optimize=_einsum_path(subscripts, ranks),
    )


def _contract_term_jvp(
    covariance: np.ndarray,
    t2: np.ndarray,
    direction_covariance: np.ndarray,
    direction_t2: np.ndarray,
    loops: tuple[int, ...],
    cross_counts: tuple[int, ...],
    removed_edges: tuple[int, ...],
) -> tuple[np.ndarray, np.ndarray]:
    subscripts, ranks = _term_subscripts(loops, cross_counts, removed_edges)
    edge_count = len(_topology_edges(loops, cross_counts))
    covariance_count = edge_count - len(removed_edges)
    operands = [covariance] * covariance_count + [t2] * len(loops)
    path = _einsum_path(subscripts, ranks)
    primal = np.einsum(subscripts, *operands, optimize=path)
    tangent = np.zeros_like(primal, dtype=np.result_type(primal, np.complex128))
    for index in range(covariance_count):
        values = list(operands)
        values[index] = direction_covariance
        tangent += np.einsum(subscripts, *values, optimize=path)
    for index in range(len(loops)):
        values = list(operands)
        values[covariance_count + index] = direction_t2
        tangent += np.einsum(subscripts, *values, optimize=path)
    return primal, tangent


def _canonical_term(
    subscripts: str,
    operand_kinds: tuple[str, ...],
    covariance: np.ndarray,
    t2: np.ndarray,
    *,
    support: np.ndarray | None = None,
    t2_slices: dict[tuple[int, ...], np.ndarray] | None = None,
) -> np.ndarray:
    input_specification, output_labels = subscripts.split("->")
    input_labels = tuple(input_specification.split(","))
    if support is not None and support.size < covariance.shape[0]:
        restricted_labels = {
            label
            for labels, kind in zip(input_labels, operand_kinds)
            if kind == "k"
            for label in labels
        }
        # Generated source labels are never covariance-contracted. Keep a
        # fail-safe for future schemas rather than scattering reduced outputs.
        if restricted_labels.isdisjoint(output_labels):
            reduced_covariance = covariance[np.ix_(support, support)]
            cache = {} if t2_slices is None else t2_slices
            operands_list: list[np.ndarray] = []
            for labels, kind in zip(input_labels, operand_kinds):
                if kind == "k":
                    operands_list.append(reduced_covariance)
                    continue
                restricted_axes = tuple(
                    axis
                    for axis, label in enumerate(labels)
                    if label in restricted_labels
                )
                reduced_t2 = cache.get(restricted_axes)
                if reduced_t2 is None:
                    reduced_t2 = t2
                    for axis in restricted_axes:
                        reduced_t2 = np.take(reduced_t2, support, axis=axis)
                    cache[restricted_axes] = reduced_t2
                operands_list.append(reduced_t2)
            operands = tuple(operands_list)
        else:
            operands = tuple(
                covariance if kind == "k" else t2 for kind in operand_kinds
            )
    else:
        operands = tuple(covariance if kind == "k" else t2 for kind in operand_kinds)
    ranks = tuple(2 if kind == "k" else 4 for kind in operand_kinds)
    return np.einsum(
        subscripts,
        *operands,
        optimize=_einsum_path(subscripts, ranks),
    )


def _canonical_term_jvp(
    subscripts: str,
    operand_kinds: tuple[str, ...],
    covariance: np.ndarray,
    t2: np.ndarray,
    direction_covariance: np.ndarray,
    direction_t2: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    operands = tuple(covariance if kind == "k" else t2 for kind in operand_kinds)
    directions = tuple(
        direction_covariance if kind == "k" else direction_t2
        for kind in operand_kinds
    )
    ranks = tuple(2 if kind == "k" else 4 for kind in operand_kinds)
    path = _einsum_path(subscripts, ranks)
    primal = np.einsum(subscripts, *operands, optimize=path)
    tangent = np.zeros_like(primal, dtype=np.result_type(primal, np.complex128))
    for index, direction in enumerate(directions):
        values = list(operands)
        values[index] = direction
        tangent += np.einsum(subscripts, *values, optimize=path)
    return primal, tangent


def _evaluate_canonical_terms(
    terms: tuple[tuple[Fraction, str, tuple[str, ...]], ...],
    covariance: np.ndarray,
    t2: np.ndarray,
    shape: tuple[int, ...],
    *,
    support: np.ndarray | None = None,
    t2_slices: dict[tuple[int, ...], np.ndarray] | None = None,
) -> np.ndarray:
    result = np.zeros(shape, dtype=np.complex128)
    for coefficient, subscripts, kinds in terms:
        result += float(coefficient) * _canonical_term(
            subscripts,
            kinds,
            covariance,
            t2,
            support=support,
            t2_slices=t2_slices,
        )
    return result


def _evaluate_canonical_terms_jvp(
    terms: tuple[tuple[Fraction, str, tuple[str, ...]], ...],
    covariance: np.ndarray,
    t2: np.ndarray,
    direction_covariance: np.ndarray,
    direction_t2: np.ndarray,
    shape: tuple[int, ...],
) -> tuple[np.ndarray, np.ndarray]:
    primal_total = np.zeros(shape, dtype=np.complex128)
    tangent_total = np.zeros(shape, dtype=np.complex128)
    for coefficient, subscripts, kinds in terms:
        primal, tangent = _canonical_term_jvp(
            subscripts,
            kinds,
            covariance,
            t2,
            direction_covariance,
            direction_t2,
        )
        primal_total += float(coefficient) * primal
        tangent_total += float(coefficient) * tangent
    return primal_total, tangent_total


def _series_polynomial_ser2(
    covariance: np.ndarray,
    t2: np.ndarray,
) -> tuple[complex, np.ndarray, np.ndarray]:
    nspin = covariance.shape[0]
    support = np.flatnonzero(
        np.any(covariance != 0.0, axis=0) | np.any(covariance != 0.0, axis=1)
    )
    t2_slices: dict[tuple[int, ...], np.ndarray] = {}
    scalar = 1.0 + _evaluate_canonical_terms(
        _SER2_SCALAR_TERMS,
        covariance,
        t2,
        (),
        support=support,
        t2_slices=t2_slices,
    )
    pair = _evaluate_canonical_terms(
        _SER2_PAIR_TERMS,
        covariance,
        t2,
        (nspin, nspin),
        support=support,
        t2_slices=t2_slices,
    )
    quad = _evaluate_canonical_terms(
        _SER2_ANTISYMMETRIZED_QUAD_TERMS,
        covariance,
        t2,
        (nspin,) * 4,
        support=support,
        t2_slices=t2_slices,
    )
    return complex(scalar), _antisymmetrize_pair(pair), _antisymmetrize_quad(quad)


def _series_polynomial_ser2_jvp(
    covariance: np.ndarray,
    t2: np.ndarray,
    direction_covariance: np.ndarray,
    direction_t2: np.ndarray,
) -> tuple[
    tuple[complex, np.ndarray, np.ndarray],
    tuple[complex, np.ndarray, np.ndarray],
]:
    nspin = covariance.shape[0]
    scalar, direction_scalar = _evaluate_canonical_terms_jvp(
        _SER2_SCALAR_TERMS,
        covariance,
        t2,
        direction_covariance,
        direction_t2,
        (),
    )
    pair, direction_pair = _evaluate_canonical_terms_jvp(
        _SER2_PAIR_TERMS,
        covariance,
        t2,
        direction_covariance,
        direction_t2,
        (nspin, nspin),
    )
    quad, direction_quad = _evaluate_canonical_terms_jvp(
        _SER2_QUAD_TERMS,
        covariance,
        t2,
        direction_covariance,
        direction_t2,
        (nspin,) * 4,
    )
    return (
        (
            complex(1.0 + scalar),
            _antisymmetrize_pair(pair),
            _antisymmetrize_quad(quad),
        ),
        (
            complex(direction_scalar),
            _antisymmetrize_pair(direction_pair),
            _antisymmetrize_quad(direction_quad),
        ),
    )


def _series_polynomial_from_topologies(
    covariance: np.ndarray,
    t2: np.ndarray,
    order: int,
) -> tuple[complex, np.ndarray, np.ndarray]:
    nspin = covariance.shape[0]
    scalar = 1.0 + 0.0j
    pair = np.zeros((nspin, nspin), dtype=np.complex128)
    quad = np.zeros((nspin,) * 4, dtype=np.complex128)
    for power in range(1, order + 1):
        for loops, cross_counts, coefficient in _TOPOLOGIES[power]:
            factor = float(coefficient)
            edges = _topology_edges(loops, cross_counts)
            scalar += factor * _contract_term(
                covariance, t2, loops, cross_counts, ()
            )
            for edge in range(len(edges)):
                pair += 2.0 * factor * _contract_term(
                    covariance, t2, loops, cross_counts, (edge,)
                )
            for first, second in permutations(range(len(edges)), 2):
                quad += 4.0 * factor * _contract_term(
                    covariance,
                    t2,
                    loops,
                    cross_counts,
                    (first, second),
                )
    return (
        complex(scalar),
        _antisymmetrize_pair(pair),
        _antisymmetrize_quad(quad),
    )


def _series_polynomial_from_topologies_jvp(
    covariance: np.ndarray,
    t2: np.ndarray,
    direction_covariance: np.ndarray,
    direction_t2: np.ndarray,
    order: int,
) -> tuple[
    tuple[complex, np.ndarray, np.ndarray],
    tuple[complex, np.ndarray, np.ndarray],
]:
    nspin = covariance.shape[0]
    scalar = 1.0 + 0.0j
    direction_scalar = 0.0 + 0.0j
    pair = np.zeros((nspin, nspin), dtype=np.complex128)
    direction_pair = np.zeros_like(pair)
    quad = np.zeros((nspin,) * 4, dtype=np.complex128)
    direction_quad = np.zeros_like(quad)
    for power in range(1, order + 1):
        for loops, cross_counts, coefficient in _TOPOLOGIES[power]:
            factor = float(coefficient)
            edges = _topology_edges(loops, cross_counts)
            primal, tangent = _contract_term_jvp(
                covariance,
                t2,
                direction_covariance,
                direction_t2,
                loops,
                cross_counts,
                (),
            )
            scalar += factor * primal
            direction_scalar += factor * tangent
            for edge in range(len(edges)):
                primal, tangent = _contract_term_jvp(
                    covariance,
                    t2,
                    direction_covariance,
                    direction_t2,
                    loops,
                    cross_counts,
                    (edge,),
                )
                pair += 2.0 * factor * primal
                direction_pair += 2.0 * factor * tangent
            for first, second in permutations(range(len(edges)), 2):
                primal, tangent = _contract_term_jvp(
                    covariance,
                    t2,
                    direction_covariance,
                    direction_t2,
                    loops,
                    cross_counts,
                    (first, second),
                )
                quad += 4.0 * factor * primal
                direction_quad += 4.0 * factor * tangent
    return (
        (
            complex(scalar),
            _antisymmetrize_pair(pair),
            _antisymmetrize_quad(quad),
        ),
        (
            complex(direction_scalar),
            _antisymmetrize_pair(direction_pair),
            _antisymmetrize_quad(direction_quad),
        ),
    )


def _series_polynomial(
    covariance: np.ndarray,
    t2: np.ndarray,
    order: int,
) -> tuple[complex, np.ndarray, np.ndarray]:
    if order == 2:
        return _series_polynomial_ser2(covariance, t2)
    return _series_polynomial_from_topologies(covariance, t2, order)


def _series_polynomial_jvp(
    covariance: np.ndarray,
    t2: np.ndarray,
    direction_covariance: np.ndarray,
    direction_t2: np.ndarray,
    order: int,
) -> tuple[
    tuple[complex, np.ndarray, np.ndarray],
    tuple[complex, np.ndarray, np.ndarray],
]:
    if order == 2:
        return _series_polynomial_ser2_jvp(
            covariance,
            t2,
            direction_covariance,
            direction_t2,
        )
    return _series_polynomial_from_topologies_jvp(
        covariance,
        t2,
        direction_covariance,
        direction_t2,
        order,
    )


def evaluate_disentangled_series(
    t1: np.ndarray,
    t2: np.ndarray,
    z: np.ndarray,
    *,
    order: int,
) -> DisentangledSeries:
    if order not in (2, 3):
        raise ValueError("the disentangled series order must be two or three")
    t1 = np.asarray(t1, dtype=np.complex128)
    t2 = np.asarray(t2, dtype=np.complex128)
    z = np.asarray(z, dtype=np.complex128)
    identity = np.eye(t1.shape[0], dtype=np.complex128)
    left_inverse = np.linalg.inv(identity - z @ t1)
    annihilation_map = np.linalg.inv(identity - t1 @ z)
    covariance = left_inverse @ z
    gaussian_pair = t1 @ left_inverse
    gaussian_norm = principal_sqrt_determinant(identity - z @ t1)
    polynomial, pair_numerator, quad_numerator = _series_polynomial(
        covariance, t2, order
    )
    if abs(polynomial) <= np.finfo(float).eps:
        raise ValueError("the truncated correlated Ser norm is numerically zero")
    induced_pair = pair_numerator / polynomial
    induced_quad = quad_numerator / polynomial - _pair_square(induced_pair)
    w1 = gaussian_pair + annihilation_map @ induced_pair @ annihilation_map.T
    w2 = _transform_quad(annihilation_map, induced_quad)
    return DisentangledSeries(
        norm=gaussian_norm * polynomial,
        w1=_antisymmetrize_pair(w1),
        w2=_antisymmetrize_quad(w2),
        scalar_polynomial=polynomial,
    )


def evaluate_disentangled_series_with_jvp(
    t1: np.ndarray,
    t2: np.ndarray,
    z: np.ndarray,
    direction_t1: np.ndarray,
    direction_t2: np.ndarray,
    *,
    order: int,
) -> DisentangledSeriesDerivative:
    if order not in (2, 3):
        raise ValueError("the disentangled series order must be two or three")
    t1 = np.asarray(t1, dtype=np.complex128)
    t2 = np.asarray(t2, dtype=np.complex128)
    z = np.asarray(z, dtype=np.complex128)
    direction_t1 = np.asarray(direction_t1, dtype=np.complex128)
    direction_t2 = np.asarray(direction_t2, dtype=np.complex128)
    identity = np.eye(t1.shape[0], dtype=np.complex128)
    left_inverse = np.linalg.inv(identity - z @ t1)
    annihilation_map = np.linalg.inv(identity - t1 @ z)
    direction_left_inverse = left_inverse @ z @ direction_t1 @ left_inverse
    direction_annihilation_map = (
        annihilation_map @ direction_t1 @ z @ annihilation_map
    )
    covariance = left_inverse @ z
    direction_covariance = direction_left_inverse @ z
    gaussian_pair = t1 @ left_inverse
    direction_gaussian_pair = (
        direction_t1 @ left_inverse + t1 @ direction_left_inverse
    )
    gaussian_norm = principal_sqrt_determinant(identity - z @ t1)
    direction_gaussian_norm = gaussian_norm * (
        -0.5 * np.trace(left_inverse @ z @ direction_t1)
    )
    (polynomial, pair_numerator, quad_numerator), (
        direction_polynomial,
        direction_pair_numerator,
        direction_quad_numerator,
    ) = _series_polynomial_jvp(
        covariance,
        t2,
        direction_covariance,
        direction_t2,
        order,
    )
    if abs(polynomial) <= np.finfo(float).eps:
        raise ValueError("the truncated correlated Ser norm is numerically zero")
    induced_pair = pair_numerator / polynomial
    direction_induced_pair = (
        direction_pair_numerator - induced_pair * direction_polynomial
    ) / polynomial
    induced_quad = quad_numerator / polynomial - _pair_square(induced_pair)
    direction_induced_quad = (
        direction_quad_numerator - (quad_numerator / polynomial) * direction_polynomial
    ) / polynomial - _pair_square_jvp(induced_pair, direction_induced_pair)
    transformed_pair = annihilation_map @ induced_pair @ annihilation_map.T
    direction_transformed_pair = (
        direction_annihilation_map @ induced_pair @ annihilation_map.T
        + annihilation_map @ direction_induced_pair @ annihilation_map.T
        + annihilation_map @ induced_pair @ direction_annihilation_map.T
    )
    w1 = gaussian_pair + transformed_pair
    direction_w1 = direction_gaussian_pair + direction_transformed_pair
    w2 = _transform_quad(annihilation_map, induced_quad)
    direction_w2 = _transform_quad_jvp(
        annihilation_map,
        direction_annihilation_map,
        induced_quad,
        direction_induced_quad,
    )
    primal = DisentangledSeries(
        norm=gaussian_norm * polynomial,
        w1=_antisymmetrize_pair(w1),
        w2=_antisymmetrize_quad(w2),
        scalar_polynomial=polynomial,
    )
    return DisentangledSeriesDerivative(
        primal=primal,
        direction_norm=(
            direction_gaussian_norm * polynomial
            + gaussian_norm * direction_polynomial
        ),
        direction_w1=_antisymmetrize_pair(direction_w1),
        direction_w2=_antisymmetrize_quad(direction_w2),
    )


