"""Bounded-rank Wick kernels for Ser2/Ser3 number projection.

The kernels implement the power-series disentanglement of Song, Henderson,
and Scuseria after treating the two-quasiparticle cluster exactly as a
Gaussian transformation.  Only the scalar polynomial and its first two
antisymmetric source derivatives are required.  Consequently no state
vector or tensor above rank four is constructed at runtime.
"""

