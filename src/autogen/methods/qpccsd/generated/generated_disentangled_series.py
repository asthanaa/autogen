def principal_sqrt_determinant(matrix: np.ndarray) -> complex:
    """Evaluate the principal square-root determinant without overflow."""

    # Some LAPACK builds emit divide/invalid warnings from the internal log
    # even when the returned complex sign and log magnitude are finite.
    with np.errstate(divide="ignore", invalid="ignore", over="ignore"):
        phase, log_magnitude = np.linalg.slogdet(np.asarray(matrix))
    if phase == 0.0:
        return 0.0 + 0.0j
    if not np.isfinite(log_magnitude):
        raise ValueError("the Gaussian overlap determinant is not finite")
    return complex(np.sqrt(complex(phase)) * np.exp(0.5 * log_magnitude))


